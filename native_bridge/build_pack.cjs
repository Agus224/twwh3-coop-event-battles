'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const {readPack, writePack} = require('../tools/pack_tool.cjs');
const base = __dirname;
const release = JSON.parse(fs.readFileSync(path.join(base, 'VERSION.json'), 'utf8'));
const VERSION = release.version;
if (!/^\d+\.\d+(\.\d+)?$/.test(VERSION)) throw Error('Invalid VERSION.json version');
const sha256 = file => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const members = {
  'script/campaign/mod/coop_event_battles.lua': fs.readFileSync(path.join(base, 'campaign_bridge.lua')),
};
// Battle side (1.1.2): CA's gb:get_army fails when the ally's unnamed army joins the player's
// alliance; without this, quest scripts die after fading the intro out (black screen).
members['script/battle/mod/coop_event_battles_battle.lua'] = fs.readFileSync(path.join(base, 'battle_fix.lua'));
members['ui/common ui/ceb_army_picker.twui.xml'] = fs.readFileSync(path.join(base, '../ui_src/ceb_army_picker.twui.xml'));
// Do not ship script/enable_console_logging: it makes the game write a new script_log_*.txt
// in the game folder on every launch, and those files are never cleaned up (1.1.1).
members['ui/campaign ui/mp_pending_action_blocking_msg.twui.xml'] = fs.readFileSync(path.join(base, '../ui_src/mp_pending_action_blocking_msg.twui.xml'));
const out = path.join(base, 'dist');
fs.mkdirSync(out, {recursive:true});
// Embed the compiled DLL so friends only need the .pack. The companion writes it next to
// Warhammer3.exe on campaign load (see ceb:extract_native_dll in network.inc.lua).
const dllPath = path.join(out, 'ceb_native_bridge.dll');
if (!fs.existsSync(dllPath)) throw Error('dist/ceb_native_bridge.dll missing: run build.cmd first, the pack must embed it');
const nativeBuild = JSON.parse(fs.readFileSync(path.join(out, 'native_build.json'), 'utf8'));
const nativeSource = crypto.createHash('sha256');
for (const name of nativeBuild.inputs) nativeSource.update(name).update(fs.readFileSync(path.join(base,name)));
if (nativeBuild.version !== VERSION || nativeBuild.dll_sha256 !== sha256(dllPath) || nativeBuild.source_sha256 !== nativeSource.digest('hex'))
  throw Error('DLL is stale or has another version. Run build.cmd before packaging.');
const script = members['script/campaign/mod/coop_event_battles.lua'].toString('utf8');
if (!script.includes('version = "' + VERSION + '"') || !script.includes('protocol = "' + release.network_protocol + '"'))
  throw Error('Companion version differs. Run python generate_companion.py.');
// Build id: hash of everything that goes into the pack, so two players can compare it in the log
// or the single-player popup and know they run the exact same build.
const CONTENT_SHA256 = (() => {
  const h = crypto.createHash('sha256');
  for (const name of Object.keys(members).sort()) h.update(name).update(members[name]);
  h.update(fs.readFileSync(dllPath));
  return h.digest('hex');
})();
const BUILD = CONTENT_SHA256.slice(0,8);
const historyFile = path.join(base,'release_history.json');
const history = fs.existsSync(historyFile) ? JSON.parse(fs.readFileSync(historyFile,'utf8')) : {};
if (history[VERSION] && history[VERSION].content_sha256 !== CONTENT_SHA256)
  throw Error('Version '+VERSION+' is already assigned to different content. Run python bump_version.py patch, regenerate and compile.');
function luaBlob(bytes) {
  const chunks = [];
  for (let start = 0; start < bytes.length; start += 4096) {
    let text = '';
    for (const b of bytes.subarray(start, start + 4096)) {
      // printable ASCII except quote and backslash stays raw; everything else is a 3-digit escape
      text += (b >= 0x20 && b <= 0x7e && b !== 0x22 && b !== 0x5c) ? String.fromCharCode(b) : '\\' + String(b).padStart(3, '0');
    }
    chunks.push('"' + text + '"');
  }
  return '-- Generated by build_pack.cjs: ceb_native_bridge.dll ' + VERSION + ', ' + bytes.length + ' bytes. Do not edit.\n' +
    'ceb_native_dll_blob = {version = "' + VERSION + '", build = "' + BUILD + '", size = ' + bytes.length + ', chunks = {\n' + chunks.join(',\n') + '\n}}\n';
}
members['script/campaign/mod/coop_event_battles_native_blob.lua'] = Buffer.from(luaBlob(fs.readFileSync(dllPath)), 'latin1');
const packFile = path.join(out, 'coop_event_battles.pack');
writePack(packFile, members);
const check = readPack(packFile);
try {
  if (check.entries.length !== Object.keys(members).length) throw Error('Wrong pack member count');
  for (const entry of check.entries) {
    const name = entry.name.replaceAll('\\', '/');
    if (!members[name] || !check.read(entry).equals(members[name])) throw Error('Pack readback mismatch: ' + name);
  }
} finally { check.close(); }
const manifest = {
  version:VERSION, build:BUILD, protocol:release.network_protocol, content_sha256:CONTENT_SHA256, pack_sha256:sha256(packFile),
  per_join_inspection:'All human clients must acknowledge matching force CQIs and participant count before native.join',
  installed:false, activated:false, live_game_validated:false,
  members:Object.keys(members),
  dll_required:'embedded in the pack (script/campaign/mod/coop_event_battles_native_blob.lua); written beside Warhammer3.exe on campaign load',
  native_api:'status(); inspect(game_interface, host_force_cqi, ally_force_cqi[, flags]); join(game_interface, host_force_cqi, ally_force_cqi[, flags]); flags 1 = single-player same-faction test',
};
const dll = path.join(out, 'ceb_native_bridge.dll');
if (fs.existsSync(dll)) manifest.dll_sha256 = sha256(dll);
fs.writeFileSync(path.join(out, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
history[VERSION] = {build:BUILD,content_sha256:CONTENT_SHA256,pack_sha256:manifest.pack_sha256,dll_sha256:manifest.dll_sha256};
fs.writeFileSync(historyFile,JSON.stringify(history,null,2)+'\n');
console.log('Verified standalone replacement pack: ' + packFile + ' (build ' + BUILD + ')');
console.log('Not installed or activated.');
