"""Generate native release metadata from VERSION.json, the single version source."""
from pathlib import Path
import json,re

ROOT=Path(__file__).resolve().parent
def prepare():
    release=json.loads((ROOT/'VERSION.json').read_text())
    version=release['version']
    if not re.fullmatch(r'\d+\.\d+(?:\.\d+)?',version): raise ValueError('Use major.minor or major.minor.patch')
    numbers=[int(x) for x in version.split('.')]
    if any(x>65535 for x in numbers): raise ValueError('Version components exceed Windows resource limit')
    numbers += [0]*(4-len(numbers))
    native_abi=int(release['native_abi'])
    (ROOT/'ceb_version.h').write_text(
        '/* Generated by prepare_version.py; edit VERSION.json instead. */\n'
        '#ifndef CEB_VERSION_H\n#define CEB_VERSION_H\n'
        f'#define CEB_BRIDGE_VERSION "{version}"\n#define CEB_BRIDGE_PROTOCOL {native_abi}\n#endif\n')
    (ROOT/'ceb_version.rc').write_text('''#include <windows.h>
1 VERSIONINFO
FILEVERSION %s
PRODUCTVERSION %s
FILEFLAGSMASK 0x3fL
FILEFLAGS 0
FILEOS VOS_NT_WINDOWS32
FILETYPE VFT_DLL
BEGIN
 BLOCK "StringFileInfo"
 BEGIN
  BLOCK "040904b0"
  BEGIN
   VALUE "FileDescription", "Co-op Event Battles Native Bridge\\0"
   VALUE "FileVersion", "%s\\0"
   VALUE "ProductName", "Co-op Event Battles\\0"
   VALUE "ProductVersion", "%s\\0"
   VALUE "OriginalFilename", "ceb_native_bridge.dll\\0"
  END
 END
 BLOCK "VarFileInfo"
 BEGIN
  VALUE "Translation", 0x409, 1200
 END
END
'''%(','.join(map(str,numbers)),','.join(map(str,numbers)),version,version))
    return release
if __name__=='__main__': print('Prepared release',prepare()['version'])
